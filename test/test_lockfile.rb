# frozen_string_literal: true

# The vetted lock (lib/axum_dsl/vetted/Cargo.lock, made by bin/vet_lock) and the check that a crate's trimmed lock
# stays inside it. The trimming itself is cargo's; test_e2e_pin covers it.
require "minitest/autorun"
require "axum_dsl"

class TestLockfile < Minitest::Test
  L = AxumDsl::Lockfile
  HEADER = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n"
  REG = "registry+https://github.com/rust-lang/crates.io-index"

  def pkg(name, version, checksum: nil, deps: [], source: REG)
    lines = ["[[package]]", %(name = "#{name}"), %(version = "#{version}")]
    lines << %(source = "#{source}") if source
    lines << %(checksum = "#{checksum || "#{name}#{version}"}") if source
    lines.concat(["dependencies = [", *deps.map { |d| %( "#{d}",) }, "]"]) unless deps.empty?
    "#{lines.join("\n")}\n"
  end

  def lock(*pkgs) = ([HEADER] + pkgs).join("\n")

  def vetted = lock(pkg("a", "1.0.0", deps: ["b 1.0.0"]), pkg("b", "1.0.0"), pkg("b", "2.0.0"),
                    pkg("axum_dsl_vetted", "0.1.0", source: nil, deps: ["a", "b 2.0.0"]))

  def test_a_trimmed_lock_is_inside
    mine = lock(pkg("b", "2.0.0"), pkg("tool", "0.2.0", source: nil, deps: ["b"]))
    assert_empty L.outside(mine, vetted)
  end

  def test_a_version_the_vetted_set_lacks_is_outside
    mine = lock(pkg("b", "3.0.0"), pkg("tool", "0.2.0", source: nil, deps: ["b"]))
    assert_equal ["b 3.0.0"], L.outside(mine, vetted)
  end

  def test_a_different_checksum_is_outside
    mine = lock(pkg("b", "2.0.0", checksum: "tampered"), pkg("tool", "0.2.0", source: nil, deps: ["b"]))
    assert_equal ["b 2.0.0"], L.outside(mine, vetted)
  end

  def test_an_unreadable_block_is_refused
    e = assert_raises(AxumDsl::CompileError) { L.parse(lock(pkg("b", "2.0.0") + "features = [\"x\"]\n")) }
    assert_includes e.message, "unreadable package block"
  end

  # The vetted resolve covers the crates every emitted Cargo.toml names, so a new always-on dependency needs a new
  # bin/vet_lock run. (The per-feature crates are covered by the examples; bin/vet_lock lists the ones that are not.)
  def test_vetted_lock_covers_the_always_on_crates
    names = L.parse(File.read(AxumDsl::Emit::VETTED_LOCK)).map { |p| p["name"] }
    assert_empty %w[axum tokio serde serde_json anyhow tikv-jemallocator libc proptest tower] - names
  end
end
